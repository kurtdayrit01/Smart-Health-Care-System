-- Smart Healthcare Management System - Supabase PostgreSQL schema
-- Run in Supabase Dashboard > SQL Editor. Safe to re-run for tables/indexes.
-- This script does not delete existing data.

CREATE TABLE IF NOT EXISTS roles (
  role_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name varchar(40) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS users (
  user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id integer NOT NULL REFERENCES roles(role_id),
  full_name varchar(120) NOT NULL,
  email varchar(160) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS departments (
  department_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_name varchar(100) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS patients (
  patient_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_code varchar(30) NOT NULL UNIQUE,
  full_name varchar(120) NOT NULL,
  birth_date date,
  sex varchar(20),
  contact_number varchar(30),
  address varchar(255),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS doctors (
  doctor_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES users(user_id),
  department_id integer NOT NULL REFERENCES departments(department_id),
  license_number varchar(60) UNIQUE,
  specialization varchar(100)
);
CREATE TABLE IF NOT EXISTS doctor_schedules (
  schedule_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id integer NOT NULL REFERENCES doctors(doctor_id),
  day_of_week varchar(9) NOT NULL CHECK (day_of_week IN ('Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday')),
  start_time time NOT NULL,
  end_time time NOT NULL,
  room varchar(30),
  CHECK (end_time > start_time)
);
CREATE TABLE IF NOT EXISTS appointments (
  appointment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id integer NOT NULL REFERENCES patients(patient_id),
  doctor_id integer NOT NULL REFERENCES doctors(doctor_id),
  appointment_datetime timestamp NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Confirmed','Completed','Cancelled')),
  reason varchar(255),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS medical_records (
  record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id integer NOT NULL REFERENCES patients(patient_id),
  doctor_id integer NOT NULL REFERENCES doctors(doctor_id),
  appointment_id integer REFERENCES appointments(appointment_id),
  diagnosis varchar(255) NOT NULL,
  notes text,
  recorded_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS medications (
  medication_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medication_name varchar(120) NOT NULL UNIQUE,
  description varchar(255)
);
CREATE TABLE IF NOT EXISTS prescriptions (
  prescription_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id integer NOT NULL REFERENCES patients(patient_id),
  doctor_id integer NOT NULL REFERENCES doctors(doctor_id),
  appointment_id integer REFERENCES appointments(appointment_id),
  prescribed_at timestamptz NOT NULL DEFAULT now(),
  instructions text
);
CREATE TABLE IF NOT EXISTS prescription_items (
  prescription_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prescription_id integer NOT NULL REFERENCES prescriptions(prescription_id) ON DELETE CASCADE,
  medication_id integer NOT NULL REFERENCES medications(medication_id),
  dosage varchar(80) NOT NULL,
  frequency varchar(80) NOT NULL,
  duration varchar(80)
);
CREATE TABLE IF NOT EXISTS invoices (
  invoice_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id integer NOT NULL REFERENCES patients(patient_id),
  appointment_id integer REFERENCES appointments(appointment_id),
  invoice_date date NOT NULL DEFAULT CURRENT_DATE,
  total_amount numeric(10,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
  status varchar(20) NOT NULL DEFAULT 'Unpaid' CHECK (status IN ('Unpaid','Partially Paid','Paid'))
);
CREATE TABLE IF NOT EXISTS invoice_items (
  invoice_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id integer NOT NULL REFERENCES invoices(invoice_id) ON DELETE CASCADE,
  item_description varchar(180) NOT NULL,
  quantity integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
  unit_price numeric(10,2) NOT NULL CHECK (unit_price >= 0)
);

-- The existing Billing UI uses a separate bills model. Keep it compatible while
-- retaining invoices/invoice_items for the academic schema and dashboard.
CREATE TABLE IF NOT EXISTS bills (
  bill_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_number varchar(80) NOT NULL UNIQUE,
  patient_id integer REFERENCES patients(patient_id) ON DELETE SET NULL,
  patient_name varchar(120) NOT NULL,
  description varchar(255) NOT NULL,
  total_amount numeric(10,2) NOT NULL CHECK (total_amount > 0),
  amount_paid numeric(10,2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0),
  bill_date date NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'Unpaid' CHECK (status IN ('Unpaid','Partially Paid','Paid')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS payments (
  payment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id integer REFERENCES invoices(invoice_id) ON DELETE CASCADE,
  bill_id integer REFERENCES bills(bill_id) ON DELETE CASCADE,
  amount numeric(10,2) NOT NULL CHECK (amount > 0),
  payment_method varchar(40) NOT NULL,
  reference_number varchar(120),
  paid_at timestamptz NOT NULL DEFAULT now(),
  CHECK (invoice_id IS NOT NULL OR bill_id IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS appointment_audit (
  audit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id integer,
  old_status varchar(20),
  new_status varchar(20),
  changed_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS invoice_item_audit (
  audit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_item_id integer,
  action_name varchar(20),
  changed_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_appt_patient ON appointments(patient_id);
CREATE INDEX IF NOT EXISTS idx_appt_doctor ON appointments(doctor_id);
CREATE INDEX IF NOT EXISTS idx_appt_datetime ON appointments(appointment_datetime);
CREATE INDEX IF NOT EXISTS idx_payments_bill ON payments(bill_id);
CREATE INDEX IF NOT EXISTS idx_payments_invoice ON payments(invoice_id);

CREATE OR REPLACE VIEW vw_appointment_details AS
SELECT a.appointment_id, a.appointment_datetime, a.status, a.reason,
       p.patient_code, p.full_name AS patient_name, d.doctor_id,
       u.full_name AS doctor_name, dep.department_name
FROM appointments a
JOIN patients p ON p.patient_id = a.patient_id
JOIN doctors d ON d.doctor_id = a.doctor_id
JOIN users u ON u.user_id = d.user_id
JOIN departments dep ON dep.department_id = d.department_id;

CREATE OR REPLACE VIEW vw_patient_billing AS
SELECT i.invoice_id, p.patient_code, p.full_name AS patient_name,
       i.invoice_date, i.total_amount, i.status
FROM invoices i JOIN patients p ON p.patient_id = i.patient_id;

CREATE OR REPLACE VIEW vw_doctor_schedule AS
SELECT s.schedule_id, d.doctor_id, u.full_name AS doctor_name,
       dep.department_name, s.day_of_week, s.start_time, s.end_time, s.room
FROM doctor_schedules s
JOIN doctors d ON d.doctor_id = s.doctor_id
JOIN users u ON u.user_id = d.user_id
JOIN departments dep ON dep.department_id = d.department_id;

CREATE OR REPLACE FUNCTION audit_appointment_status_change()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status IS DISTINCT FROM NEW.status THEN
    INSERT INTO appointment_audit(appointment_id, old_status, new_status)
    VALUES (OLD.appointment_id, OLD.status, NEW.status);
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_appointment_status ON appointments;
CREATE TRIGGER trg_appointment_status AFTER UPDATE ON appointments
FOR EACH ROW EXECUTE FUNCTION audit_appointment_status_change();

CREATE OR REPLACE FUNCTION audit_invoice_item_insert()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO invoice_item_audit(invoice_item_id, action_name)
  VALUES (NEW.invoice_item_id, 'INSERT');
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_invoice_item_insert ON invoice_items;
CREATE TRIGGER trg_invoice_item_insert AFTER INSERT ON invoice_items
FOR EACH ROW EXECUTE FUNCTION audit_invoice_item_insert();

